namespace DelmondesCodeLabs_GestaoComercial.Domain.DTOs
{
    #region ABC Product DTO
    /// <summary>
    /// Represents a product's sales performance for the ABC curve analysis.
    /// </summary>
    public class AbcProductDto
    {
        #region Properties
        /// <summary>
        /// Gets or sets the product's name.
        /// </summary>
        public string ProductName { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the total quantity of this product sold.
        /// </summary>
        public decimal TotalQuantitySold { get; set; }

        /// <summary>
        /// Gets or sets the total net revenue generated by this product.
        /// </summary>
        public decimal TotalRevenue { get; set; }
        #endregion Properties
    }
    #endregion ABC Product DTO
}